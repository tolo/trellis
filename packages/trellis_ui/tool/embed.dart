import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

import 'src/bundle.dart';

String embeddedSource(Directory root) {
  final assets = bundleAssets(root);
  final fragments = {
    for (final f in sourceFiles(Directory('${root.path}/assets/fragments'), '.html'))
      'trellis-ui/${f.uri.pathSegments.last.replaceFirst(RegExp(r'\.html$'), '')}': f.readAsBytesSync(),
  };
  final out = StringBuffer('// GENERATED by tool/embed.dart. Do not edit.\n\n');
  void strings(String name, Map<String, String> entries) {
    out.writeln('const $name = <String, String>{');
    for (final entry in entries.entries) {
      final text = entry.value;
      if (text.length <= 100 && entry.key.length + text.length + 9 <= 120) {
        out.writeln("  '${entry.key}': '$text',");
        continue;
      }
      out.writeln("  '${entry.key}':");
      if (text.isEmpty) out.writeln("      '',");
      for (var i = 0; i < text.length; i += 100) {
        final end = i + 100 < text.length ? i + 100 : text.length;
        out.writeln("      '${text.substring(i, end)}'${end == text.length ? ',' : ''}");
      }
    }
    out.writeln('};\n');
  }

  strings('assetBase64', assets.map((k, v) => MapEntry(k, base64Encode(v))));
  strings('assetDigests', assets.map((k, v) => MapEntry(k, sha256.convert(v).toString())));
  strings('fragmentBase64', fragments.map((k, v) => MapEntry(k, base64Encode(v))));
  strings('fragmentDigests', fragments.map((k, v) => MapEntry(k, sha256.convert(v).toString())));
  return '${out.toString().trimRight()}\n';
}

Future<void> main(List<String> args) async {
  if (args.any((a) => a != '--check')) throw ArgumentError('usage: dart run tool/embed.dart [--check]');
  final root = Directory.fromUri(Platform.script.resolve('../'));
  final target = File('${root.path}/lib/src/embedded_assets.g.dart');
  final source = embeddedSource(root);
  if (args.contains('--check')) {
    if (!target.existsSync() || target.readAsStringSync() != source) {
      throw StateError('Embedded asset drift: ${target.path}');
    }
    stdout.writeln('Embedded check: assets and fragments byte-identical');
  } else {
    target.writeAsStringSync(source);
    stdout.writeln('Embedded ${bundleAssets(root).length} assets and suite fragments');
  }
}
