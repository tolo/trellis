import 'dart:convert';
import 'dart:io';

import 'tsx_scan.dart';

class StyleRule {
  StyleRule(this.selector, this.text, this.hooks);
  final String selector;
  final String text; // full rule text, wrapper-relative
  final Set<String> hooks;
}

/// Splits the body of `.style-<name> { ... }` into depth-1 rules (comments dropped).
List<StyleRule> parseStyleRules(String css, String style) {
  final open = css.indexOf('.style-$style {');
  if (open < 0) throw StateError('no .style-$style wrapper');
  var body = css.substring(css.indexOf('{', open) + 1, css.lastIndexOf('}'));
  body = body.replaceAll(RegExp(r'/\*.*?\*/', dotAll: true), '');
  final rules = <StyleRule>[];
  var i = 0;
  while (i < body.length) {
    final brace = body.indexOf('{', i);
    if (brace < 0) break;
    var depth = 1, j = brace + 1;
    while (j < body.length && depth > 0) {
      if (body[j] == '{') depth++;
      if (body[j] == '}') depth--;
      j++;
    }
    final selector = body.substring(i, brace).trim();
    rules.add(
      StyleRule(selector, body.substring(i, j).trim(), {
        for (final m in RegExp(r'\.(cn-[\w-]+)').allMatches(selector)) m[1]!,
      }),
    );
    i = j;
  }
  return rules;
}

bool _tagAtLeast(String tag, String from) {
  List<int> v(String t) => t.split('@').last.split('.').map(int.parse).toList();
  final a = v(tag), b = v(from);
  for (var i = 0; i < 3; i++) {
    if (a[i] != b[i]) return a[i] > b[i];
  }
  return true;
}

String _renameHooks(String s) => s.replaceAllMapped(RegExp(r'(?<![\w-])cn-'), (_) => 'trellis-');

class Generator {
  Generator(this.root, this.pins);
  final Directory root;
  final Map<String, dynamic> pins;
  String get vendorPath => '${root.path}/vendor/shadcn/${(pins['shadcn'] as Map)['tag']}';
  Future<void> _write(String path, String text) async {
    final f = File(path);
    await f.parent.create(recursive: true);
    await f.writeAsString(text);
  }

  String _customUtilities() {
    final source = File('$vendorPath/tailwind.css').readAsStringSync();
    // The legacy .shimmer fallback is page-wide. @utility shimmer already supplies
    // the reduced-motion behavior when a component actually applies the utility.
    final end = source.indexOf('/* Kept for backwards compatibility.');
    return end < 0 ? source : source.substring(0, end);
  }

  String _tokens() {
    final json =
        jsonDecode(File('$vendorPath/colors-${pins['baseColor']}.json').readAsStringSync()) as Map<String, dynamic>;
    final v4 = json['cssVarsV4'] as Map<String, dynamic>;
    final light = Map<String, dynamic>.from(v4['light'] as Map);
    final dark = Map<String, dynamic>.from(v4['dark'] as Map);
    final buf = StringBuffer('@theme inline {\n');
    for (final k in light.keys.where((k) => k != 'radius')) {
      buf.writeln('  --color-$k: var(--$k);');
    }
    // Radius scale: copied from apps/v4/app/globals.css (docs-site theme block), not from the registry JSON.
    const scale = {'sm': '0.6', 'md': '0.8', 'xl': '1.4', '2xl': '1.8', '3xl': '2.2', '4xl': '2.6'};
    for (final e in scale.entries) {
      buf.writeln('  --radius-${e.key}: calc(var(--radius) * ${e.value});');
    }
    buf.writeln('  --radius-lg: var(--radius);\n}\n');
    buf.writeln(':root {');
    light.forEach((k, v) => buf.writeln('  --$k: $v;'));
    buf.writeln('}\n\n.dark {');
    dark.forEach((k, v) => buf.writeln('  --$k: $v;'));
    buf.writeln('}');
    return buf.toString();
  }

  Future<GenReport> generate({Directory? output}) async {
    final p = pins['shadcn'] as Map<String, dynamic>;
    final dir = vendorPath;
    final style = pins['style'] as String;
    final scan = ScanResult();
    final tsx = [for (final c in (pins['components'] as List).cast<String>()) File('$dir/ui/$c.tsx')]
      ..sort((a, b) => a.path.compareTo(b.path));
    for (final f in tsx) {
      scanTsx(f.readAsStringSync(), f.uri.pathSegments.last, scan);
    }
    final scope = scan.allHooks;
    final rules = parseStyleRules(File('$dir/style-$style.css').readAsStringSync(), style);
    final kept = rules.where((r) => r.hooks.any(scope.contains)).toList();

    final structural = StringBuffer();
    final names = scan.hooks.keys.toList()..sort();
    var emitted = 0;
    final skip = ((pins['structuralSkip'] as Map?) ?? const {}).cast<String, Map<String, dynamic>>();
    final skipped = <String>[];
    for (final n in names) {
      final h = scan.hooks[n]!;
      if (h.structural.isEmpty) continue;
      final s = skip[n];
      if (s != null && _tagAtLeast(p['tag'] as String, s['from'] as String)) {
        skipped.add(_renameHooks(n));
        continue;
      }
      emitted++;
      structural.writeln('  .${_renameHooks(n)} {\n    @apply ${h.structural.join(' ')};\n  }');
    }

    final entry = StringBuffer()
      ..writeln(
        '/*! Trellis UI. GENERATED by tool/port.dart from shadcn-ui/ui ${p['tag']} (${(p['commit'] as String).substring(0, 7)}), '
        'base ${pins['base']}, style $style. Do not edit.',
      )
      ..writeln(
        '   Derived from shadcn/ui, MIT License, Copyright (c) 2023 shadcn. See vendor/shadcn/${p['tag']}/LICENSE.md. */',
      )
      ..writeln('@layer theme, base, components, utilities, trellis-hand;')
      ..writeln('@import "tailwindcss/theme.css" layer(theme);')
      ..writeln('@import "tailwindcss/utilities.css" layer(utilities) source(none);')
      ..writeln('@import "../vendor/tw-animate/tw-animate.css";')
      ..writeln(_customUtilities())
      ..writeln('@custom-variant dark (&:is(.dark *));\n')
      ..writeln('@layer theme {\n${_tokens()}\n}')
      ..writeln('\n/* structural utilities scanned from TSX string literals that carry a cn- hook */')
      ..writeln('@layer components {')
      ..write(structural)
      ..writeln('\n  /* style-$style.css, unwrapped, ${kept.length} of ${rules.length} rules */');
    for (final r in kept) {
      entry.writeln('  ${_renameHooks(r.text).replaceAll('\n', '\n  ')}');
    }
    entry.writeln('}');

    final out = (output ?? Directory('${root.path}/generated')).path;
    await _write('$out/entry.css', entry.toString());

    // Marker classes the hand layer must put in the HTML (they cannot be @apply'd).
    final markers = <String, List<String>>{
      for (final n in names)
        if (scan.hooks[n]!.markers.isNotEmpty) _renameHooks(n): scan.hooks[n]!.markers.toList()..sort(),
    };
    final collisions = {
      for (final n in names)
        if (scan.hooks[n]!.groups > 1) _renameHooks(n): scan.hooks[n]!.groups,
    };
    final report = {
      'tag': p['tag'],
      'tsxFiles': tsx.length,
      'hooksPrimary': scan.hooks.length,
      'hooks': [for (final n in (scan.allHooks.toList()..sort())) _renameHooks(n)],
      'hooksSecondary': scan.secondaryHooks.difference(scan.hooks.keys.toSet()).length,
      'hooksWithStructural': emitted,
      'styleRulesTotal': rules.length,
      'styleRulesKept': kept.length,
      'styleRulesWithoutTsxHook': rules.where((r) => !r.hooks.any(scope.contains)).length,
      'slots': (scan.slots.toList()..sort()),
      'dataAttrs': (scan.dataAttrs.toList()..sort()),
      'markers': markers,
      'hooksSeenInSeveralLiterals': collisions,
      'structuralSkipped': skipped,
      'orphanLiterals': [
        for (final o in scan.orphans) {'file': o.file, 'line': o.line, 'slot': o.slot, 'literal': o.preview},
      ],
    };
    await _write('$out/report.json', '${const JsonEncoder.withIndent('  ').convert(report)}\n');
    stdout.writeln(
      'generated $out/entry.css: ${report['hooksPrimary']} primary hooks, $emitted with structural classes, '
      '${kept.length}/${rules.length} style rules, ${scan.orphans.length} orphan literals, ${scan.slots.length} slots',
    );
    return GenReport()..stats.addAll(report);
  }
}

class GenReport {
  final stats = <String, Object?>{};
}
